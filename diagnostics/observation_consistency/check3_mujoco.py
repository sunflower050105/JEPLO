#!/usr/bin/env python3
"""Run diagnostic trials using a private controller build and the existing runner.

The imported runner is changed only in this process: its command function sets a
per-trial trace destination. The baseline launcher on disk stays unchanged.
"""

import argparse
import os
from pathlib import Path
import runpy
import sys
from common import ROOT, new_output, sha256, write_json


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--repo", type=Path, default=ROOT)
    p.add_argument(
        "--audit-build",
        type=Path,
        required=True,
        help="Output directory from prepare_mujoco_capture.py",
    )
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--max-records", type=int, default=5000)
    p.add_argument("benchmark_args", nargs=argparse.REMAINDER)
    a = p.parse_args()
    if a.max_records < 1:
        p.error("max-records must be positive")
    repo = a.repo.resolve()
    build = a.audit_build.resolve()
    binary = build / "build/deploy_observation_audit"
    if not binary.is_file():
        p.error(f"Build the separate diagnostic controller first: {binary}")
    if not (build / "instrumentation.diff").is_file():
        p.error("audit-build must be generated by prepare_mujoco_capture.py")
    forwarded = (
        a.benchmark_args[1:] if a.benchmark_args[:1] == ["--"] else a.benchmark_args
    )
    out = new_output(a.output)
    script = repo / "deployment/evaluation/velocity_benchmark/run.py"
    sys.path.insert(0, str(script.parent))
    loaded = runpy.run_path(str(script), run_name="observation_audit_mujoco")
    ns = loaded["main"].__globals__
    original = ns["commands"]

    def commands(args, directory, *pos, **kw):
        os.environ["JEPLO_OBSERVATION_AUDIT_DIR"] = str(directory / "observations")
        os.environ["JEPLO_OBSERVATION_AUDIT_MAX_RECORDS"] = str(a.max_records)
        return original(args, directory, *pos, **kw)

    ns["commands"] = commands
    sys.argv = [
        str(script),
        "--terrain",
        "benchmark_stairs",
        "--speeds",
        "0.8",
        "--repeats",
        "1",
        "--duration",
        "30",
        "--seed",
        "0",
        "--stair-contact-friction",
        "1.0",
        "--lidar-hz",
        "50",
        "--stacked-frames",
        "10",
        "--downsample-rate",
        "8",
        "--occlusions",
        "standard",
        *forwarded,
        "--model-dir",
        "my_policy_r2",
        "--deploy-bin",
        str(binary),
        "--keep-diagnostics",
        "--output",
        str(out / "benchmark"),
    ]
    write_json(
        out / "launch.json",
        dict(
            argv=sys.argv,
            baseline_runner_sha256=sha256(script),
            build_manifest_sha256=sha256(build / "build_manifest.json"),
            diagnostic=True,
        ),
    )
    return ns["main"]()


if __name__ == "__main__":
    raise SystemExit(main())
